import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({timezoneId:'Asia/Kolkata'});
const page=await context.newPage();
await page.route('https://ipapi.co/json/',route=>route.fulfill({json:{country_code:'IN'}}));
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173');
await page.waitForURL('**country=in&currency=INR');
assert.equal(await page.locator('#region').inputValue(),'in');
for(const img of await page.locator('.product-art img').all()){await img.scrollIntoViewIfNeeded();await img.evaluate(el=>el.decode());assert.ok(await img.evaluate(el=>el.naturalWidth>0));}
await page.selectOption('#region','us');
await page.locator('[data-product="macbook-air"]').first().click();
await page.locator('.spec-button[data-spec="Memory"][data-value="24GB"]').click();
const selectedVariant=new URL(page.url()).pathname.split('/').at(-1);
assert.ok(selectedVariant.includes('24gb'));
assert.equal(await page.locator('.spec-button[data-spec="Memory"][data-value="24GB"]').getAttribute('aria-current'),'true');
await page.selectOption('#region','in');
assert.equal(new URL(page.url()).pathname.split('/').at(-1),selectedVariant);
assert.equal(await page.locator('.spec-button[data-spec="Memory"][data-value="24GB"]').getAttribute('aria-current'),'true');
assert.ok(page.url().includes(selectedVariant));
await page.reload();
assert.equal(new URL(page.url()).pathname.split('/').at(-1),selectedVariant);
assert.equal(await page.locator('.spec-button[data-spec="Memory"][data-value="24GB"]').getAttribute('aria-current'),'true');
assert.equal(await page.locator('#region').inputValue(),'in');
assert.ok(page.url().includes('currency=INR'));
await page.goBack();
assert.equal(new URL(page.url()).pathname.split('/').at(-1),selectedVariant);
assert.equal(await page.locator('.spec-button[data-spec="Memory"][data-value="24GB"]').getAttribute('aria-current'),'true');
assert.ok(page.url().includes('currency=USD'));
await page.goForward();
assert.ok(page.url().includes('currency=INR'));
await page.locator('[data-home]').first().click();
assert.equal(await page.locator('#region').inputValue(),'in');
assert.ok(page.url().includes('currency=INR'));
await page.locator('[data-filter="Mac"]').click();
assert.equal(await page.locator('.product-card').count(),2);
await page.locator('#search').fill('no product');
assert.equal(await page.locator('.product-card').count(),0);
await page.locator('#search').fill('');
for(const width of [375,768,1440]){
 await page.setViewportSize({width,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
}
await page.locator('[data-product="macbook-air"]').first().click();
await page.setViewportSize({width:375,height:900});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Detail overflow');
for(const img of await page.locator('.product-art img').all()){await img.scrollIntoViewIfNeeded();await img.evaluate(el=>el.decode());assert.ok(await img.evaluate(el=>el.naturalWidth>0));}
const savedPage=await page.context().newPage();
await savedPage.goto('http://localhost:5173');
assert.equal(await savedPage.locator('#region').inputValue(),'in');
await savedPage.close();
const fallbackPage=await browser.newPage({timezoneId:'Asia/Kolkata'});
await fallbackPage.route('https://ipapi.co/json/',route=>route.abort());
await fallbackPage.goto('http://localhost:5173');
await fallbackPage.waitForURL('**country=in&currency=INR');
await fallbackPage.close();
const racePage=await browser.newPage({timezoneId:'America/New_York'});
let release;const gate=new Promise(resolve=>release=resolve);
await racePage.route('https://ipapi.co/json/',async route=>{await gate;await route.fulfill({json:{country_code:'IN'}});});
await racePage.goto('http://localhost:5173');
await racePage.selectOption('#region','jp');
const response=racePage.waitForResponse('https://ipapi.co/json/');release();await response;
assert.equal(await racePage.locator('#region').inputValue(),'jp');
assert.ok(racePage.url().includes('currency=JPY'));
await racePage.close();
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser regression passed: variant, preferences, reload, history, navigation, search, responsive overflow.');
